(function(){
'use strict';

function getInput(label){
  return Array.from(document.querySelectorAll('#section-site [data-label]')).find(function(el){
    return el.dataset.label===label;
  });
}

function chainCode(name){
  const clean=String(name||'').toUpperCase().replace(/[^A-Z0-9 ]+/g,' ').trim();
  if(!clean)return '';
  const words=clean.split(/\s+/).filter(Boolean);
  if(words.length===1)return words[0].slice(0,4).padEnd(4,'X');
  const initials=words.map(function(w){return w.charAt(0);}).join('');
  if(initials.length>=3)return initials.slice(0,4);
  return (words[0].slice(0,3)+words[1].charAt(0)).slice(0,4);
}

function hashSite(text){
  let h=2166136261;
  for(let i=0;i<text.length;i++){
    h^=text.charCodeAt(i);
    h=Math.imul(h,16777619);
  }
  return (h>>>0).toString(16).toUpperCase().padStart(8,'0').slice(0,6);
}

function updateSiteId(){
  const chain=getInput('Restaurant / chain');
  const id=getInput('Site ID');
  if(!id)return;

  id.readOnly=true;
  id.setAttribute('aria-readonly','true');
  id.title='Generated by AEM from the restaurant chain and site address.';
  id.style.background='#f3f5f7';

  const address=getInput('Street address');
  const city=getInput('City');
  const state=getInput('State');
  const zip=getInput('ZIP');
  const chainName=chain&&chain.value.trim();
  const code=chainCode(chainName);
  const siteKey=[chainName,address&&address.value.trim(),city&&city.value.trim(),state&&state.value.trim(),zip&&zip.value.trim()].join('|').toUpperCase();

  if(!code){
    if(!id.value||id.dataset.aemGenerated==='true')id.value='';
    return;
  }

  const hasAddress=!!((address&&address.value.trim())||(city&&city.value.trim())||(zip&&zip.value.trim()));
  if(!hasAddress){
    if(!id.value||id.dataset.aemGenerated==='true')id.value=code+'-PENDING';
    id.dataset.aemGenerated='true';
    id.dispatchEvent(new Event('input',{bubbles:true}));
    return;
  }

  const next=code+'-'+hashSite(siteKey);
  if(id.value!==next){
    id.value=next;
    id.dataset.aemGenerated='true';
    id.dispatchEvent(new Event('input',{bubbles:true}));
    id.dispatchEvent(new Event('change',{bubbles:true}));
  }
}

function start(){
  updateSiteId();
  document.addEventListener('input',function(e){
    if(!e.target||!e.target.dataset)return;
    if(['Restaurant / chain','Street address','City','State','ZIP'].includes(e.target.dataset.label))setTimeout(updateSiteId,0);
  },true);
  document.addEventListener('change',function(e){
    if(!e.target||!e.target.dataset)return;
    if(['Restaurant / chain','Street address','City','State','ZIP'].includes(e.target.dataset.label))setTimeout(updateSiteId,0);
  },true);
  const root=document.getElementById('section-content');
  if(root&&window.MutationObserver){
    const observer=new MutationObserver(function(){setTimeout(updateSiteId,0);});
    observer.observe(root,{childList:true,subtree:true});
  }
}

if(document.readyState==='loading')document.addEventListener('DOMContentLoaded',start);
else start();
})();
